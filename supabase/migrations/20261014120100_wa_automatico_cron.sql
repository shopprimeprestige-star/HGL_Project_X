-- programma_hook_cron legge sito e chiave pubblica da app_config e, se mancano,
-- NON programma e lo dice (vedi 20261005150000). Per spegnerlo:
--     SELECT cron.unschedule('wa-auto-1min');
-- ─────────────────────────────────────────────────────────────────────────────
